import streamlit as st

def render_er_diagram():
    st.caption("Understanding the underlying MongoDB collections for the Automated Lab Result Interpretation System")

    # Display the ER diagram image (local file in repository)
    st.image(
        "src/module/Automated_Lab_Result_Interpretation_System/pages/ER_Diagram.jpeg",
        use_container_width=True,
    )

    st.markdown("### 🗄️ MongoDB Collections Overview")
    st.markdown("""
    - **`lab_results`**: Stores raw patient test results (e.g. Glucose levels, Hemoglobin) and timestamps.
    - **`interpretation_rules`**: Defines the medical logic conditions (e.g. `TestValue > 125`), rule severity, and related pattern IDs.
    - **`patterns`**: Describes complex, multi-variable logic to detect specific syndromes or conditions based on combinations of lab results.
    - **`recommendations`**: Stores the outputs generated by the Evaluation Engine, mapping the actionable advice to a specific patient and the source rule/pattern that triggered it.
    """)

    st.info("🔄 **Data Flow**: `lab_results` + `interpretation_rules` (+ `patterns`) ➡️ **Evaluation Engine** ➡️ `recommendations`")
