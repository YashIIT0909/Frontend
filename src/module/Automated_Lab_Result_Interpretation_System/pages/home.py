import streamlit as st
from src.module.Automated_Lab_Result_Interpretation_System.api import get_overview_stats

def render_home():
    st.success("Automated Lab Result Interpretation workflow overview. This landing page shows the core architecture and live statistics from the backend system.")

    col1, col2 = st.columns(2)
    with col1:
        st.markdown("### 📥 Input Entities")
        st.info("The data and logic that flow into the engine:")
        st.success("1️⃣ **Raw Lab Results** (e.g., Hemoglobin, Glucose levels)")
        st.success("2️⃣ **Interpretation Rules** (The logic conditions your engine uses)")
        st.success("3️⃣ **Complex Patterns** (Multi-variable rules)")

    with col2:
        st.markdown("### 📤 Output Entities")
        st.info("The actionable advice generated by the engine:")
        st.success("1️⃣ **Interpretation Status** (Normal, Abnormal, Critical)")
        st.success("2️⃣ **Generated Recommendations** (Actionable advice for doctors)")
        st.success("3️⃣ **Follow-Up Test Directives** (Passed to subsequent modules)")

    st.divider()

    st.markdown("### 📊 Quick Stats Overview")
    st.caption("Fetching live data from global GET endpoints...")

    stats, error = get_overview_stats()

    m1, m2, m3, m4 = st.columns(4)
    m1.metric("⚙️ Total Rules Active", stats["rules"])
    m2.metric("🧩 Total Patterns Active", stats["patterns"])
    m3.metric("🔬 Total Results Evaluated", stats["results"])
    m4.metric("📋 Total Recommendations", stats["recommendations"])

    if error:
        st.warning(f"Some backend stats are currently unavailable: {error}")
